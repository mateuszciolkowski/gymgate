// Embeds drizzle-kit's SQL migrations in a TS module so Metro needs no `.sql` loader.
// Run via `npm run db:generate` (after drizzle-kit generate). Output: src/db/migrations/migrations.ts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "migrations");
const journal = JSON.parse(readFileSync(join(dir, "meta/_journal.json"), "utf8"));
const migrations = journal.entries.map((e) => ({
  sql: readFileSync(join(dir, `${e.tag}.sql`), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
  folderMillis: e.when,
  hash: e.tag,
}));
writeFileSync(
  join(dir, "migrations.ts"),
  `// GENERATED by src/db/genMigrations.mjs from the drizzle-kit output. Do not edit.\n` +
    `export interface Migration {\n  sql: string[];\n  folderMillis: number;\n  hash: string;\n}\n\n` +
    `export const migrations: Migration[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
