// Generates src/theme/themes.generated.ts from docs/tokeny-motywow.json (extracted from frontend/src/index.css).
//
// Usage:  node tools/gen-themes.mjs           write the file
//         node tools/gen-themes.mjs --check   exit 1 if the committed file is stale
//
// CSS -> React Native conversion rules
//  1. Plain hex / rgba() colours are copied verbatim (React Native understands both).
//  2. `color-mix(in srgb, <var> N%, transparent)` (--gg-glow) is resolved to `rgba(r, g, b, N/100)`,
//     using the theme's own --gg-btn-bg. Result is the explicit string stored in `colors.glow`.
//  3. `linear-gradient(135deg, btn-bg, btn-hover)` (--gg-grad-btn) becomes a stop array for
//     expo-linear-gradient: { colors: [btnBg, btnHover], start: {x:0,y:0}, end: {x:1,y:1} }
//     (135deg = top-left to bottom-right; exact for squares, a close approximation for wide buttons).
//  4. `box-shadow: a, b` (--gg-shadow, --gg-shadow-elevated) becomes an array of RN `boxShadow`
//     objects { offsetX, offsetY, blurRadius, spreadRadius, color } (style prop `boxShadow`, new architecture).
//  5. `backdrop-filter: blur()` has no token: the blur itself is rendered with expo-blur by the
//     components; `colors.navBg` is the translucent tint placed on top of it.
//  6. `--gg-error` falls back to #EF4444 when a theme does not override it (as in the CSS :root).
//  7. Source quirk: the JSON extractor swallowed the real `--gg-btn-hover` of `dark` into a comment
//     line, so it is taken from index.css (:root) via OVERRIDES below.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "docs/tokeny-motywow.json");
const OUT = join(root, "src/theme/themes.generated.ts");

export const THEME_ORDER = [
  "dark",
  "steel",
  "graphite",
  "violet",
  "ember",
  "crimson",
  "light",
  "blossom",
  "sky",
  "sand",
  "sage",
  "slate",
];
const DARK = new Set(["dark", "steel", "graphite", "violet", "ember", "crimson"]);
const OVERRIDES = { dark: { "--gg-btn-hover": "#059669" } };

const COLOR_TOKENS = {
  bg: "--gg-bg",
  surface: "--gg-surface",
  surface2: "--gg-surface2",
  surface3: "--gg-surface3",
  border: "--gg-border",
  borderMed: "--gg-border-med",
  borderStrong: "--gg-border-strong",
  text: "--gg-text",
  textSub: "--gg-text-sub",
  textMuted: "--gg-text-muted",
  a1: "--gg-a1",
  a2: "--gg-a2",
  btnBg: "--gg-btn-bg",
  btnHover: "--gg-btn-hover",
  tagBg: "--gg-tag-bg",
  tagText: "--gg-tag-text",
  recordBg: "--gg-record-bg",
  recordText: "--gg-record-text",
  navBg: "--gg-nav-bg",
  activeBorder: "--gg-active-border",
  activeGlow: "--gg-active-glow",
  activeBg: "--gg-active-bg",
  error: "--gg-error",
};

function hexToRgb(hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!m) throw new Error(`Expected #RRGGBB, got "${hex}"`);
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

function parseShadow(css) {
  // "0 1px 3px rgba(0, 0, 0, 0.4), 0 4px 12px rgba(0, 0, 0, 0.25)"
  const parts = css.split(/,(?![^(]*\))/).map((s) => s.trim());
  return parts.map((p) => {
    const m =
      /^(-?\d+(?:\.\d+)?)(?:px)?\s+(-?\d+(?:\.\d+)?)(?:px)?\s+(\d+(?:\.\d+)?)(?:px)?\s+(?:(-?\d+(?:\.\d+)?)(?:px)?\s+)?(rgba?\([^)]*\))$/.exec(
        p,
      );
    if (!m) throw new Error(`Cannot parse shadow "${p}"`);
    return {
      offsetX: Number(m[1]),
      offsetY: Number(m[2]),
      blurRadius: Number(m[3]),
      spreadRadius: Number(m[4] ?? 0),
      color: m[5],
    };
  });
}

function buildTheme(name, raw) {
  const t = { ...raw, ...(OVERRIDES[name] ?? {}) };
  const colors = {};
  for (const [key, token] of Object.entries(COLOR_TOKENS)) {
    const v = t[token] ?? (token === "--gg-error" ? "#EF4444" : undefined);
    if (v === undefined) throw new Error(`Theme ${name} is missing ${token}`);
    colors[key] = v;
  }
  const [r, g, b] = hexToRgb(colors.btnBg);
  colors.glow = `rgba(${r}, ${g}, ${b}, 0.35)`;
  return {
    name,
    isDark: DARK.has(name),
    colors,
    gradBtn: {
      colors: [colors.btnBg, colors.btnHover],
      start: { x: 0, y: 0 },
      end: { x: 1, y: 1 },
    },
    shadow: parseShadow(t["--gg-shadow"]),
    shadowElevated: parseShadow(t["--gg-shadow-elevated"]),
  };
}

export function generate() {
  const json = JSON.parse(readFileSync(SRC, "utf8"));
  const names = Object.keys(json.motywy);
  if (names.length !== THEME_ORDER.length || !THEME_ORDER.every((n) => names.includes(n))) {
    throw new Error(`Expected themes ${THEME_ORDER.join(", ")}, got ${names.join(", ")}`);
  }
  const themes = Object.fromEntries(THEME_ORDER.map((n) => [n, buildTheme(n, json.motywy[n])]));
  return (
    "// GENERATED by tools/gen-themes.mjs from docs/tokeny-motywow.json. Do not edit; run `npm run gen:themes`.\n" +
    'import type { Theme } from "./types";\n\n' +
    `export const THEME_NAMES = ${JSON.stringify(THEME_ORDER)} as const;\n\n` +
    `export const themes = ${JSON.stringify(themes, null, 2)} as const satisfies Record<(typeof THEME_NAMES)[number], Theme>;\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = generate();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {
      /* missing */
    }
    if (current !== out) {
      console.error("src/theme/themes.generated.ts is stale. Run `npm run gen:themes`.");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, out);
  }
}
